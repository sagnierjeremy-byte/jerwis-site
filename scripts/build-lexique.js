async function updateHub(data) {
  let html = await readFile(HUB_PATH, "utf8");
  const az = renderAzList(data.terms);
  const expressCards = renderExpressCards(data.terms);
  if (!html.includes(HUB_START) || !html.includes(HUB_END)) {
    throw new Error(`Markers ${HUB_START} / ${HUB_END} absents de lexique.html`);
  }
  html = html.replace(new RegExp(`${HUB_START}[\\s\\S]*?${HUB_END}`), az);
  if (html.includes(EXPRESS_START) && html.includes(EXPRESS_END)) {
    html = html.replace(new RegExp(`${EXPRESS_START}[\\s\\S]*?${EXPRESS_END}`), expressCards);
  } else {
    const nextHtml = html.replace(
      /(<div class="lex-express-grid">\n)[\s\S]*?(\n\s*<\/div>\n\s*<\/div>\n<\/section>\n\n<!-- Mini-marquee avant le CTA final -->)/,
      `$1${expressCards}$2`,
    );
    if (nextHtml === html) {
      throw new Error("Bloc .lex-express-grid introuvable dans lexique.html");
    }
    html = nextHtml;
  }
  html = html.replace(
    /<!-- Schema\.org : DefinedTermSet \(glossaire\) -->\n<script type="application\/ld\+json">[\s\S]*?<\/script>/,
    renderDefinedTermSet(data),
  );
  await writeFile(HUB_PATH, habillerHtml(html, "lexique.html").t);
}

async function cleanupGeneratedPages() {
  await mkdir(OUT_DIR, { recursive: true });
  const files = await readdir(OUT_DIR).catch(() => []);
  await Promise.all(files.map(async (file) => {
    if (!file.endsWith(".html")) return;
    const fullPath = join(OUT_DIR, file);
    const content = await readFile(fullPath, "utf8");
    if (content.includes(GENERATED_MARKER)) await unlink(fullPath);
  }));
}

async function writeTermPages(data) {
  await cleanupGeneratedPages();
  const pageTerms = data.terms.filter((term) => term.page);
  await Promise.all(pageTerms.map((term) => (
    writeFile(join(OUT_DIR, `${term.slug}.html`), habillerHtml(renderTermPage(term, data.terms), `lexique/${term.slug}.html`).t)
  )));
  return pageTerms;
}

function renderSitemapBlock(pageTerms) {
  const urls = pageTerms
    .toSorted((a, b) => a.title.localeCompare(b.title, "fr", { sensitivity: "base" }))
    .map((term) => `  <url>
    <loc>${SITE_URL}/lexique/${term.slug}</loc>
    <lastmod>${term.lastmod || TODAY}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>${PRIORITY_MAP[term.priority] || "0.55"}</priority>
  </url>`)
    .join("\n\n");
  return `${SITEMAP_START}
${urls}
${SITEMAP_END}`;
}

async function updateSitemap(pageTerms) {
  let sitemap = await readFile(SITEMAP_PATH, "utf8");
  sitemap = sitemap.replace(
    /(<loc>https:\/\/jerwis\.fr\/lexique<\/loc>\s*<lastmod>)([^<]+)(<\/lastmod>)/,
    `$1${TODAY}$3`,
  );
  const block = renderSitemapBlock(pageTerms);
  if (sitemap.includes(SITEMAP_START) && sitemap.includes(SITEMAP_END)) {
    sitemap = sitemap.replace(new RegExp(`${SITEMAP_START}[\\s\\S]*?${SITEMAP_END}`), block);
  } else {
    sitemap = sitemap.replace(/\n\s*<!-- Pages légales -->/, `\n\n${block}\n\n  <!-- Pages légales -->`);
  }
  await writeFile(SITEMAP_PATH, sitemap);
}

async function main() {
  const checkOnly = process.argv.includes("--check");
  const data = JSON.parse(await readFile(DATA_PATH, "utf8"));
  validate(data);
  const pageTerms = data.terms.filter((term) => term.page);

  if (!checkOnly) {
    await updateHub(data);
    await writeTermPages(data);
    await updateSitemap(pageTerms);
  }

  console.log(`Lexique OK · ${data.terms.length} termes · ${pageTerms.length} pages dédiées${checkOnly ? " · check only" : ""}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
